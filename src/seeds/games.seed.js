async function seedGames(Console) {
  const consuls = await Console.find({});
  const consoleMap = {};
  for (const c of consuls) {
    consoleMap[c.slug] = c._id;
  }

  const GameModel = Console.db.model('Game');

  // 1. Seed legal playable games (homebrew, public domain, open source)
  const allPlayableGames = [...homebrewGames, ...additionalHomebrews, ...pdGames];
  for (const hg of allPlayableGames) {
    const consoleId = consoleMap[hg.consoleSlug];
    if (!consoleId) {
      console.warn(`Console not found for slug: ${hg.consoleSlug}`);
      continue;
    }
    const doc = {
      ...hg,
      slug: slugify(hg.consoleSlug + '-' + hg.title),
      consoleId,
    };
    delete doc.consoleSlug;
    await GameModel.create(doc);
  }
  console.log(`Seeded ${allPlayableGames.length} legal non-copyright playable games.`);

  // 2. Seed encyclopedic wiki games
  for (const [slug, games] of Object.entries(gamesByConsole)) {
    const consoleId = consoleMap[slug];
    if (!consoleId) {
      console.warn(`Console not found for slug: ${slug}`);
      continue;
    }

    const gameDocs = games.map(([title, year, publisher, developer, genre, players, rating]) =>
      makeGames(title, year, publisher, developer, genre, players, rating, slug)
    );

    for (const game of gameDocs) {
      game.consoleId = consoleId;
    }

    await GameModel.insertMany(gameDocs);
    const count = await GameModel.countDocuments({ consoleId });
    await Console.findByIdAndUpdate(consoleId, { gamesCount: count });
    console.log(`Seeded ${gameDocs.length} wiki games for ${slug} (total: ${count})`);
  }
}

module.exports = seedGames;
