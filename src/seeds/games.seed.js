function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function makeGames(title, year, publisher, developer, genre, players, rating, consoleSlug) {
  const slug = slugify(consoleSlug + '-' + title);
  return {
    title,
    slug,
    year,
    publisher,
    developer,
    genre,
    description: `«${title}» — ${genre.toLowerCase()} от ${publisher}, выпущенный в ${year} году. Эта игра стала знаковой для своей платформы и получила признание критиков и игроков по всему миру.`,
    shortDescription: `${title} — ${genre.toLowerCase()} (${year}), разработанный ${developer}.`,
    players,
    rating,
    screenshots: [
      `/images/screenshots/${slug}-scene-1.svg`,
      `/images/screenshots/${slug}-scene-2.svg`,
      `/images/screenshots/${slug}-scene-3.svg`,
      `/images/screenshots/${slug}-scene-4.svg`
    ],
    accessories: [],
    tags: [genre, `${year}`, publisher],
    licenseType: 'Каталог ретро-классики',
    licenseAuthor: publisher,
    licenseUrl: '',
    isPlayableOnline: false,
    isHomebrew: false,
    romFile: null,
  };
}

