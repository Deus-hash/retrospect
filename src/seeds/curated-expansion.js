function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const DIR_TO_CONSOLE = {
  nes: 'dendy-nes',
  snes: 'snes',
  megadrive: 'sega-mega-drive',
  mastersystem: 'sega-master-system',
  atari2600: 'atari-2600',
  pcengine: 'pc-engine',
  n64: 'nintendo-64',
  playstation: 'playstation',
  saturn: 'sega-saturn',
};

function makeCurated(
  dir,
  file,
  title,
  year,
  developer,
  genre,
  players,
  rating,
  shortDescription,
  description,
  licenseType,
  licenseUrl,
  isHomebrew = true
) {
  const consoleSlug = DIR_TO_CONSOLE[dir];
  const slug = slugify(`${consoleSlug}-${title}`);
  const hasRom = Boolean(file);
  return {
    title,
    consoleSlug,
    year,
    publisher: developer,
    developer,
    genre,
    description,
    shortDescription,
    players,
    rating,
    screenshots: [`/images/screenshots/real/${slug}.png`],
    accessories: [],
    tags: [genre, String(year), isHomebrew ? 'Homebrew' : 'Freeware', developer.split(',')[0].trim()],
    licenseType,
    licenseAuthor: developer,
    licenseUrl,
    isPlayableOnline: hasRom,
    isHomebrew,
    romFile: hasRom ? `/roms/${dir}/${file}` : null,
    _candKey: hasRom ? `${dir}__${file}.png` : `${slug}.png`,
  };
}

